"""Doc comments and the `newr docs` generator (SPEC.md section 6,
section 19, M6 Phase 3).

`///` doc comments (frozen in M6, SPEC section 24.2 idea 14) attach to
the declaration or statement directly below them (see
compiler/parser.py `_collect_doc`). This module turns them into
Markdown:

- `api_markdown()` renders the stdlib API reference from
  compiler/modules.py, the single source of truth for signatures.
  Every entry there carries a `doc` string (and a `sig` string where
  the signature cannot be derived from the params, e.g. overloads
  and optionals). The stdlib has no newr source declarations to hang
  a `///` comment on (builtins are Python data, and redeclaring one
  in newr source is a checker error), so the `doc` field IS the
  stdlib member's doc comment, stored with its signature.
- `examples_markdown(root)` renders one section per program in
  `root/examples/*.newr`, from the `///` comments in the source.
- `generate_docs(out_dir, root)` writes `api.md` (always) and
  `examples.md` (when an examples directory exists) and returns the
  file names written. The committed files under docs/ are generated
  output: regenerate with `newr docs` and commit the result.

Generated files are deterministic: the same input always renders the
same bytes, so a test can regenerate into a temp directory and diff
against the committed files.
"""

from __future__ import annotations

import re
from pathlib import Path

from . import __version__
from .db_limits import DB_MEMBERS
from .modules import BUILTINS, METHODS, MODULES
from .parser import parse

# Display names for the METHODS receiver keys (SPEC.md section 12.4).
_RECEIVER_NAMES = {
    "str": "str",
    "list": "list[T]",
    "dict": "dict[str, T]",
    "set": "set[T]",
    "nullable": "T?",
    "Result": "Result[T, E]",
}

_PARAM_NAMES = ("x", "a", "b", "c", "d")

_FENCE_RE = re.compile(r"```newr\n(.*?)```", re.DOTALL)


def _type_str(t) -> str:
    if isinstance(t, str):
        return t
    return str(t)


def _method_sig(receiver: str, name: str, entry: dict) -> str:
    params = entry.get("params", [])
    rendered = ", ".join(
        f"{_PARAM_NAMES[i]}: {_type_str(p)}"
        for i, p in enumerate(params))
    sig = f"{receiver}.{name}({rendered})"
    ret = entry.get("return")
    if ret is not None:
        sig += f" -> {_type_str(ret)}"
    return sig


def _header(title: str) -> list[str]:
    return [
        f"# {title}",
        "",
        "Generated by `newr docs` (newr "
        f"{__version__}). Do not edit by hand: edit the `///` doc "
        "comments in the source (or the `doc` strings in "
        "`compiler/modules.py` for stdlib members) and regenerate.",
        "",
    ]


def api_markdown() -> str:
    """The stdlib API reference (SPEC.md section 12)."""
    lines = _header("newr API reference")
    lines += [
        "The standard library, versioned with the language (SPEC.md "
        "section 12). Core modules are available on every target; "
        "named modules work by name without an import. `json` and "
        "HTTP `fetch` are v1.1, not v1 (section 12.3).",
        "",
        "## Core builtins",
        "",
        "Available without an import.",
        "",
    ]
    for name, entry in BUILTINS.items():
        lines += [f"### `{name}`", "", f"`{entry['sig']}`", "",
                  entry["doc"], ""]
    lines += [
        "### `log`",
        "",
        "`log expr` (statement) / `log.info/warn/error(msg)`",
        "",
        "Writes to the program's logger. `log` is a statement, not a "
        "call, and `log.info` / `log.warn` / `log.error` are the "
        "levelled forms (SPEC.md section 12.1). `t()` for i18n lives "
        "in the discord module (SPEC.md section 15), not here.",
        "",
        "## Core modules",
        "",
    ]
    for module, members in MODULES.items():
        for name, entry in members.items():
            lines += [f"### `{module}.{name}`", "",
                      f"`{entry['sig']}`", "", entry["doc"], ""]
    lines += [
        "## db module (SPEC.md section 12.5)",
        "",
        "SQLite, sync, one connection per handle. The handle is an "
        "`int` (fd style). `db.query` returns a typed struct list, "
        "resolved from the expected type at the call site. Every db "
        "call throws on failure.",
        "",
    ]
    for name, entry in DB_MEMBERS.items():
        lines += [f"### `db.{name}`", "",
                  f"`{entry['sig']}`", "", entry["doc"], ""]
    lines += [
        "## Methods (SPEC.md section 12.4)",
        "",
        "Methods on values. The receiver type is shown first.",
        "",
    ]
    for receiver, members in METHODS.items():
        display = _RECEIVER_NAMES[receiver]
        lines += [f"### `{display}`", ""]
        for name, entry in members.items():
            sig = _method_sig(display, name, entry)
            lines += [f"- `{sig}`: {entry['doc']}"]
        lines += [""]
    return "\n".join(lines)


def _program_items(prog):
    """Every documented node in a parsed program, in file order."""
    items = []
    for node in (prog.imports + prog.functions + prog.structs
                 + prog.enums + prog.test_blocks + prog.commands
                 + prog.events + prog.tasks + prog.strings
                 + prog.stores + prog.stmts):
        items.append(node)
    if prog.bot is not None:
        items.append(prog.bot)
    items.sort(key=lambda node: node.span.start_byte)
    return items


def _kind_of(node) -> str:
    name = type(node).__name__
    for suffix in ("Decl", "Block"):
        if name.endswith(suffix):
            name = name[: -len(suffix)]
    if name == "Test":
        return "test block"
    return name.lower()


def _node_name(node) -> str:
    return getattr(node, "name", None) or getattr(node, "key", None) \
        or "(top-level statement)"


def example_markdown(path: Path) -> str:
    """One example program's docs, from its `///` comments."""
    source = path.read_text(encoding="utf-8")
    prog = parse(source, str(path))
    items = _program_items(prog)
    lines = [f"## `{path.name}`", ""]
    if prog.file_doc:
        lines += [prog.file_doc, ""]
    documented = [node for node in items if node.doc]
    for node in documented:
        lines += [f"### {_kind_of(node)} `{_node_name(node)}`", "",
                  node.doc, ""]
    if not prog.file_doc and not documented:
        lines += ["No `///` doc comments yet.", ""]
    return "\n".join(lines)


def examples_markdown(root: Path) -> str:
    """Docs for every program in `root/examples/*.newr`."""
    lines = _header("newr example programs")
    lines += [
        "One section per program in `examples/`, from the `///` doc "
        "comments in the source. Every program here checks, builds, "
        "and runs; see SPEC.md section 21 for the language tour.",
        "",
    ]
    for path in sorted((root / "examples").glob("*.newr")):
        lines.append(example_markdown(path))
    return "\n".join(lines)


def generate_docs(out_dir: Path, root: Path) -> list[str]:
    """Write the generated docs into `out_dir`; return file names."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    api_path = out_dir / "api.md"
    api_path.write_text(api_markdown(), encoding="utf-8")
    written.append("api.md")
    if (root / "examples").is_dir():
        examples_path = out_dir / "examples.md"
        examples_path.write_text(examples_markdown(root),
                                 encoding="utf-8")
        written.append("examples.md")
    return written


def extract_newr_samples(path: Path) -> list[tuple[Path, str]]:
    """Every ```newr fenced block in a Markdown file."""
    text = path.read_text(encoding="utf-8")
    return [(path, match.group(1)) for match in _FENCE_RE.finditer(text)]


if __name__ == "__main__":
    import sys

    out = Path(sys.argv[sys.argv.index("--out") + 1]) \
        if "--out" in sys.argv else Path("docs")
    root = Path.cwd()
    for name in generate_docs(out, root):
        print(f"wrote {out / name}")
