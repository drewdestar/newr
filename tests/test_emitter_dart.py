import tempfile
import unittest
from pathlib import Path

from compiler.checker import check_program
from compiler.discord_check import check_discord, discord_providers
from compiler.resolver import resolve_file, resolve_source

ROOT = Path(__file__).resolve().parent.parent
RT_DART_SRC = ROOT / "compiler" / "newr_rt.dart"

# The Dart SDK lives in ~/dart-sdk (installed for M5); fall back to
# the PATH when it is not there (e.g. CI, where setup-dart
# provides it).
_DART_BIN = Path.home() / "dart-sdk" / "dart-sdk" / "bin"
DART = shutil.which("dart", path=str(_DART_BIN)) or shutil.which("dart")

try:
    from compiler.emitter_dart import EmitterError, emit_program as emit_dart
    HAS_DART_EMITTER = True
except ImportError:
    HAS_DART_EMITTER = False


def full_program(src, filename="<test>.newr"):
    """Resolve + check a source string; assert it is clean."""
    resolved = resolve_source(src, filename)
    diags = list(resolved.diagnostics)
    diags += check_program(
        resolved.program,
        providers=discord_providers(resolved.program)).diagnostics
    diags += check_discord(resolved.program)
    errs = [d for d in diags if d.is_error()]
    assert not errs, [f"{d.code}: {d.message}" for d in errs]
    return resolved.program


def emit_dart_src(src, filename="<test>.newr", stem="Main"):
    """Emit a checked program to Dart; returns the EmitResult."""
    program = full_program(src, filename)
    return emit_dart(program, main_path=filename,
                     sources={filename: src}, output_stem=stem)


def emit_dart_main_text(src, filename="<test>.newr", stem="Main"):
    """The emitted text of the main output file."""
    result = emit_dart_src(src, filename, stem)
    return result.files[result.main_file]


def run_dart_src(src, filename="<test>.newr", stem="Main",
                 argv=None, env=None, files=None):
    """Emit to a temp dir, copy newr_rt.dart if needed, run with dart.

    Returns (stdout, stderr, returncode). `files` maps extra
    .newr filenames to sources (for file imports).
    """
    result = emit_dart_src(src, filename, stem)
    with tempfile.TemporaryDirectory() as d:
        for name, text in result.files.items():
            (Path(d) / name).write_text(text, encoding="utf-8")
        if result.uses_rt:
            (Path(d) / "newr_rt.dart").write_text(
                RT_DART_SRC.read_text(encoding="utf-8"), encoding="utf-8")
        proc = subprocess.run(
            [DART, result.main_file, *(argv or [])],
            capture_output=True, text=True, cwd=d, env=env)
        return proc.stdout, proc.stderr, proc.returncode


def run_dart_ok(src, filename="<test>.newr", stem="Main",
                argv=None, env=None):
    stdout, stderr, code = run_dart_src(src, filename, stem, argv, env)
    assert code == 0, f"exit {code}\nstdout: {stdout}\nstderr: {stderr}"
    return stdout


