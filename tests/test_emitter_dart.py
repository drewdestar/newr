def _emit_shop_result():
    """Emit SHOP from a real temp dir so its `import "shop_items.newr"`
    resolves (the shop_items source is copied from examples/).
    Returns the full EmitResult (all emitted files)."""
    from compiler.resolver import resolve_file
    items = (ROOT / "examples" / "shop_items.newr").read_text(encoding="utf-8")
    with tempfile.TemporaryDirectory() as d:
        (Path(d) / "shop_items.newr").write_text(items, encoding="utf-8")
        main = Path(d) / "shop.newr"
        main.write_text(SHOP, encoding="utf-8")
        resolved = resolve_file(main)
        diags = list(resolved.diagnostics)
        diags += check_program(
            resolved.program,
            providers=discord_providers(resolved.program)).diagnostics
        diags += check_discord(resolved.program)
        errs = [x for x in diags if x.is_error()]
        assert not errs, [f"{x.code}: {x.message}" for x in errs]
        sources = {
            str(main): SHOP,
            str(Path(d) / "shop_items.newr"): items,
        }
        return emit_dart(resolved.program, main_path=str(main),
                         sources=sources, output_stem="shop")


def emit_shop_text():
    """Emit SHOP from a real temp dir; the main file's text."""
    result = _emit_shop_result()
    return result.files[result.main_file]


def _pub_get(d):
    """Run `dart pub get` in dir d (offline first, then online).
    Raises unittest.SkipTest when the packages cannot be fetched."""
    proc = subprocess.run([DART, "pub", "get", "--offline"],
                          capture_output=True, text=True, cwd=d, timeout=120)
    if proc.returncode != 0:
        proc = subprocess.run([DART, "pub", "get"],
                              capture_output=True, text=True, cwd=d,
                              timeout=300)
    if proc.returncode != 0:
        raise unittest.SkipTest(f"dart pub get failed:\n{proc.stderr}")
    return proc


def _write_result(result, d):
    for name, text in result.files.items():
        (Path(d) / name).write_text(text, encoding="utf-8")
    if result.uses_rt:
        (Path(d) / "newr_rt.dart").write_text(
            RT_DART_SRC.read_text(encoding="utf-8"), encoding="utf-8")


def compile_dart_result(result):
    """Write an EmitResult (+ newr_rt.dart when used) to a temp dir,
    pub get, and run `dart analyze` over every .dart file.
    Returns the analyze CompletedProcess."""
    with tempfile.TemporaryDirectory() as d:
        _write_result(result, d)
        if "pubspec.yaml" in result.files:
            _pub_get(d)
        dart_files = [str(p) for p in Path(d).glob("*.dart")]
        return subprocess.run([DART, "analyze", *dart_files],
                              capture_output=True, text=True, cwd=d,
                              timeout=300)


def assert_compiles(testcase, result):
    proc = compile_dart_result(result)
    testcase.assertEqual(proc.returncode, 0,
                         f"dart analyze failed:\n{proc.stdout}\n"
                         f"{proc.stderr}")


def run_bot_main(result, env=None):
    """Write an EmitResult to a temp dir, pub get, and run the main
    file with plain `dart` (the package config now exists), with
    DISCORD_TOKEN removed from the environment unless `env` sets
    it. Returns the CompletedProcess."""
    with tempfile.TemporaryDirectory() as d:
        _write_result(result, d)
        if "pubspec.yaml" in result.files:
            _pub_get(d)
        run_env = dict(os.environ)
        run_env.pop("DISCORD_TOKEN", None)
        if env:
            run_env.update(env)
        return subprocess.run([DART, result.main_file],
                              capture_output=True, text=True, cwd=d,
                              env=run_env, timeout=120)


