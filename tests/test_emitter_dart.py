"""Tests for the Dart emitter (compiler/emitter_dart.py, M5).

TDD RED first: written before the emitter existed. The
`emit_dart_src` helper runs the full front-end pipeline (resolve +
core check + discord check) and emits Dart; `run_dart_src` also
executes the emitted program with dart and returns its stdout.

Every test pins a decision from BUILD_REPORT.md §21 (decisions
K1–K13) or a SPEC rule the emitter must preserve — including the
Dart-specific traps (sound null safety: nullable types take `?`,
a `late` top-level let is assigned in main(), checked int64 via
BigInt range checks because Dart ints wrap silently, Python-repr
float rendering via NewrRt.floatStr, capture-by-value via snapshot
locals, `math.floor`/`math.ceil` are double methods, not
top-level functions, and `Map` has no `.get` — it is `m[k]`).
"""

