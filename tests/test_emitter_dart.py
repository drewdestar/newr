@unittest.skipUnless(DART, "a Dart SDK is not installed")
@unittest.skipUnless(HAS_DART_EMITTER, "compiler/emitter_dart.py is missing")
class TestDartSemantics(unittest.TestCase):
    def test_top_level_let_is_late_and_assigned_in_main(self):
        text = emit_dart_main_text(
            'let x: int = 40 + 2\nprint x\n', "<test>.newr", "Main")
        self.assertIn("late int x;", text)
        self.assertIn("x = NewrRt.add(40, 2);", text)

    def test_struct_emits_named_ctor_and_runs(self):
        src = (
            "struct Point:\n"
            "  x: int\n"
            "  y: int\n\n"
            "let p = Point(x: 1, y: 2)\n"
            'print p\n')
        self.assertEqual(run_dart_ok(src), "Point(x: 1, y: 2)\n")
        text = emit_dart_main_text(src, "<test>.newr", "Main")
        self.assertIn("Point({required this.x, required this.y});", text)
        self.assertIn("Point(x: 1, y: 2)", text)

    def test_enum_emits_class_and_runs(self):
        src = (
            "enum Shade:\n"
            "  Red\n"
            "  Green\n\n"
            "let s = Shade.Red\n"
            'print s\n')
        self.assertEqual(run_dart_ok(src), "Shade.Red\n")

    def test_enum_fielded_variant_runs(self):
        src = (
            "enum Shape:\n"
            "  Circle(radius: float)\n"
            "  Square(side: float)\n\n"
            "let c = Shape.Circle(radius: 1.5)\n"
            "match c:\n"
            "  Shape.Circle(radius: r):\n"
            "    print r\n"
            "  Shape.Square(side: s):\n"
            "    print s\n")
        self.assertEqual(run_dart_ok(src), "1.5\n")

    def test_nullable_types_take_question_mark(self):
        src = (
            "let x: int? = none\n"
            "print x\n")
        self.assertEqual(run_dart_ok(src), "none\n")
        text = emit_dart_main_text(src, "<test>.newr", "Main")
        self.assertIn("late int? x;", text)

    def test_float_renders_python_repr(self):
        # Dart's double.toString would give "10000000000000000.0"
        # for 1e16; newr wants Python's "1e+16".
        self.assertEqual(run_dart_ok('print 1e16\n'), "1e+16\n")
        self.assertEqual(run_dart_ok('print 0.00001\n'), "1e-05\n")

    def test_dict_get_uses_index_not_dot_get(self):
        src = (
            'let d = {"a": 1}\n'
            'print d.get("a", 0)\n'
            'print d.get("z", 0)\n')
        self.assertEqual(run_dart_ok(src), "1\n0\n")
        text = emit_dart_main_text(src, "<test>.newr", "Main")
        self.assertNotIn(".get(", text)

    def test_math_floor_ceil_are_double_methods(self):
        src = 'print math.floor(2.7)\nprint math.ceil(2.1)\n'
        self.assertEqual(run_dart_ok(src), "2\n3\n")
        text = emit_dart_main_text(src, "<test>.newr", "Main")
        self.assertIn("(2.7).floor()", text)
        self.assertIn("(2.1).ceil()", text)

    def test_env_get_with_default_is_non_null(self):
        src = (
            'let v = env.get("NEWR_DART_TEST_ABSENT_XYZ", "dflt")\n'
            'print v\n')
        self.assertEqual(run_dart_ok(src), "dflt\n")
        text = emit_dart_main_text(src, "<test>.newr", "Main")
        self.assertIn('NewrRt.envGet("NEWR_DART_TEST_ABSENT_XYZ", "dflt")!',
                      text)

    def test_overflow_raises_not_wraps(self):
        # Dart ints wrap silently; the emitter must check via the
        # runtime, so this fails at runtime with a NewrError.
        src = 'print 9223372036854775807 + 1\n'
        stdout, stderr, code = run_dart_src(src)
        self.assertNotEqual(code, 0)
        self.assertIn("integer overflow", stderr)

    def test_result_propagate_runs(self):
        src = (
            "fn div(a: int, b: int) -> Result[int, error]:\n"
            "  return try a / b\n\n"
            "fn half(x: int) -> Result[int, error]:\n"
            "  let h = div(10, x)?\n"
            "  return ok(h)\n\n"
            "let r = half(2)\n"
            "print r.unwrap()\n")
        self.assertEqual(run_dart_ok(src), "5\n")


