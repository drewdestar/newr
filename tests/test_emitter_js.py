import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from compiler.checker import check_program
from compiler.discord_check import check_discord, discord_providers
from compiler.resolver import resolve_source

ROOT = Path(__file__).resolve().parent.parent
RT_JS_SRC = ROOT / "compiler" / "newr_rt.js"
NODE = shutil.which("node")

try:
    from compiler.emitter_js import EmitterError, emit_program as emit_js
    HAS_JS_EMITTER = True
except ImportError:
    HAS_JS_EMITTER = False


def full_program(src, filename="<test>.newr"):
    """Resolve + check a source string; assert it is clean."""
    resolved = resolve_source(src, filename)
    diags = list(resolved.diagnostics)
    diags += check_program(
        resolved.program,
        providers=discord_providers(resolved.program)).diagnostics
    diags += check_discord(resolved.program)
    errs = [d for d in diags if d.is_error()]
    assert not errs, [f"{d.code}: {d.message}" for d in errs]
    return resolved.program


def emit_js_src(src, filename="<test>.newr"):
    """Emit a checked program to JS; returns the EmitResult."""
    program = full_program(src, filename)
    return emit_js(program, main_path=filename,
                   sources={filename: src})


def emit_js_main_text(src, filename="<test>.newr"):
    """The emitted text of the main output file."""
    result = emit_js_src(src, filename)
    return result.files[result.main_file]


def run_js_src(src, filename="<test>.newr", argv=None, env=None):
    """Emit to a temp dir, copy newr_rt.js if needed, run under node.

    Returns (stdout, stderr, returncode).
    """
    result = emit_js_src(src, filename)
    with tempfile.TemporaryDirectory() as d:
        for name, text in result.files.items():
            (Path(d) / name).write_text(text, encoding="utf-8")
        if result.uses_rt:
            (Path(d) / "newr_rt.js").write_text(
                RT_JS_SRC.read_text(encoding="utf-8"), encoding="utf-8")
        proc = subprocess.run(
            [NODE, str(Path(d) / result.main_file), *(argv or [])],
            capture_output=True, text=True, cwd=d, env=env)
        return proc.stdout, proc.stderr, proc.returncode


def run_js_ok(src, filename="<test>.newr", argv=None, env=None):
    stdout, stderr, code = run_js_src(src, filename, argv, env)
    assert code == 0, f"exit {code}\nstdout: {stdout}\nstderr: {stderr}"
    return stdout


