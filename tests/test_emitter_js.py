@unittest.skipUnless(NODE, "node is not installed")
@unittest.skipUnless(HAS_JS_EMITTER, "compiler/emitter_js.py is missing")
class TestPrecedence(unittest.TestCase):
    def test_unary_minus_takes_the_whole_sum(self):
        # newr: `-a + b` is `-(a + b)` — ints lower to checked
        # helpers (neg(add(a, b))); floats keep bare operators.
        text = emit_js_main_text("let a = 1\nlet b = 2\nlet x = -a + b\n"
                                 "print x\n")
        self.assertIn("neg(add(a, b))", text)
        ftext = emit_js_main_text("let a = 1.0\nlet b = 2.0\n"
                                  "let x = -a + b\nprint x\n")
        self.assertIn("-(a + b)", ftext)
        self.assertEqual(run_js_ok("let a = 1\nlet b = 2\nlet x = -a + b\n"
                                   "print x\n"), "-3\n")

    def test_unary_minus_power(self):
        # J-trap: `-a ** 2` is a SyntaxError in JS (unary before **),
        # so the emitter must parenthesise the power. (The checker
        # rejects `float ** int` — `**` needs same-type operands —
        # so the float form pins the parenthesization: `**` lowers
        # to powFloat/powInt calls, and the unary minus wraps the
        # whole call in parentheses.)
        ftext = emit_js_main_text("let a = 2.0\nprint -a ** 2.0\n")
        self.assertIn("-(powFloat(a, 2.0))", ftext)
        self.assertEqual(run_js_ok("print -2 ** 2\n"), "-4\n")
        self.assertEqual(run_js_ok("let x = (-2) ** 2\nprint x\n"), "4\n")

    def test_not_takes_the_whole_and(self):
        text = emit_js_main_text(
            "let a = true\nlet b = false\nlet x = not a and b\nprint x\n")
        self.assertIn("!(a && b)", text)
        self.assertEqual(run_js_ok(
            "let a = true\nlet b = false\nlet x = not a and b\nprint x\n"),
            "true\n")

    def test_power_is_right_associative(self):
        text = emit_js_main_text("let x = 2 ** 3 ** 2\nprint x\n")
        self.assertIn("powInt(2n, powInt(3n, 2n))", text)
        ftext = emit_js_main_text("let x = 2.0 ** 3.0 ** 2.0\nprint x\n")
        self.assertIn("powFloat(2.0, powFloat(3.0, 2.0))", ftext)
        self.assertEqual(run_js_ok("print 2 ** 3 ** 2\n"), "512\n")

    def test_parens_preserved_where_needed(self):
        self.assertEqual(run_js_ok("let x = (1 + 2) * 3\nprint x\n"), "9\n")
        self.assertEqual(run_js_ok("print 1 + 2 * 3\n"), "7\n")
        self.assertEqual(run_js_ok("print 10 - (3 - 1)\n"), "8\n")
        self.assertEqual(run_js_ok("print true or false and false\n"),
                         "true\n")

    def test_ternary(self):
        self.assertEqual(run_js_ok("print 1 > 0 ? \"yes\" : \"no\"\n"),
                         "yes\n")
        self.assertEqual(
            run_js_ok("print false ? 1 : true ? 2 : 3\n"), "2\n")

    def test_and_or_are_js_operators(self):
        text = emit_js_main_text("print true and false\n")
        self.assertIn("true && false", text)
        text = emit_js_main_text("print true or false\n")
        self.assertIn("true || false", text)


