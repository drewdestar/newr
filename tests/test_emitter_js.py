"""Tests for the JavaScript emitter (compiler/emitter_js.py, M3).

TDD RED first: written before the emitter existed. The `emit_js_src`
helper runs the full front-end pipeline (resolve + core check +
discord check) and emits JavaScript; `run_js_src` also executes the
emitted program under Node and returns its stdout.

Every test pins a decision from BUILD_REPORT.md §17 (decisions
J1–J12) or a SPEC rule the emitter must preserve — including the
JS-specific traps (BigInt ints, `-x ** y` is a SyntaxError in JS,
Python-repr float rendering, capture-by-value via IIFE snapshots).
"""

import json
