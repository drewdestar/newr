"""Tests for the rs app packager (SPEC.md section 22.2, M8d Phase 2).

The smoke test builds examples/hello.newr for target rs via the
`./newr` launcher (the same pattern as TestBuildApp in
test_cli.py), calls `package_rs` on the emitted files, runs the
artifact binary, and asserts the output. The rustc path is fast
(about a second for hello); the cargo path (`cargo build
--release` for a db/http/json/ui program) takes minutes on a cold
release cache on this VM, so it is verified by hand and timed in
BUILD_REPORT.md, not in this suite.

Timeouts here are deliberately very loose: this VM has a small
CPU and several agents run in parallel, so even a one-second
rustc build can take far longer wall-clock.
"""

import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parent.parent
LAUNCHER = ROOT / "newr"

from compiler.app_pack import AppPackError, SCRATCH_ROOT
from compiler.app_pack_rs import (
    CARGO_TARGET_DIR,
    TOOLCHAIN,
    _bin_name_from_cargo_toml,
    _require_cargo,
    _require_rustc,
    package_rs,
)


def run_cli(*args, cwd=None):
    # The build step is check plus emit only, seconds even on a
    # loaded VM; 600 s is a generous ceiling, not an expectation.
    return subprocess.run([sys.executable, str(LAUNCHER), *args],
                          capture_output=True, text=True, cwd=cwd,
                          timeout=600)


def _staging_leftovers(prefix):
    """Staging dirs under SCRATCH_ROOT with the given prefix."""
    if not SCRATCH_ROOT.is_dir():
        return set()
    return {p.name for p in SCRATCH_ROOT.iterdir()
            if p.is_dir() and p.name.startswith(prefix)}


class TestToolchainDetectedLive(unittest.TestCase):
    def test_toolchain_versions_are_live(self):
        # rustc and cargo are installed on this VM (EVAL.md
        # section 11 pins 1.99.1); TOOLCHAIN must carry their live
        # versions, not a hardcoded guess and not "unknown".
        if TOOLCHAIN["rustc"] == "unknown":
            self.skipTest("rustc is not installed on this VM")
        if TOOLCHAIN["cargo"] == "unknown":
            self.skipTest("cargo is not installed on this VM")
        for tool in ("rustc", "cargo"):
            self.assertRegex(TOOLCHAIN[tool], r"^\d+\.\d+\.\d+$",
                             f"{tool} version {TOOLCHAIN[tool]!r} "
                             f"is not a live version number")

    def test_missing_rustc_raises_naming_install(self):
        with mock.patch("compiler.app_pack_rs._find_tool",
                        return_value=None):
            with self.assertRaises(AppPackError) as caught:
                _require_rustc()
            self.assertIn("rustc", str(caught.exception))
            self.assertIn("install", str(caught.exception).lower())

    def test_missing_cargo_raises_naming_install(self):
        with mock.patch("compiler.app_pack_rs._find_tool",
                        return_value=None):
            with self.assertRaises(AppPackError) as caught:
                _require_cargo()
            self.assertIn("cargo", str(caught.exception))
            self.assertIn("install", str(caught.exception).lower())


class TestBinNameFromCargoToml(unittest.TestCase):
    def test_first_bin_name_wins(self):
        # The bot Cargo.toml has two [[bin]] entries; the first is
        # the program binary, the second the deploy script.
        text = (
            "[package]\n"
            "name = \"hello-bot\"\n"
            "version = \"1.0.0\"\n"
            "edition = \"2021\"\n"
            "default-run = \"hello_bot\"\n"
            "\n"
            "[[bin]]\n"
            "name = \"hello_bot\"\n"
            "path = \"hello_bot.rs\"\n"
            "\n"
            "[[bin]]\n"
            "name = \"hello_bot_deploy\"\n"
            "path = \"hello_bot_deploy.rs\"\n"
            "\n"
            "[dependencies]\n"
            "serenity = \"=0.12.5\"\n"
        )
        self.assertEqual(_bin_name_from_cargo_toml(text), "hello_bot")

    def test_plain_cargo_toml_bin_name(self):
        text = (
            "# Generated by newr - do not edit by hand.\n"
            "[package]\n"
            "name = \"mod-db\"\n"
            "version = \"1.0.0\"\n"
            "edition = \"2021\"\n"
            "\n"
            "[[bin]]\n"
            "name = \"mod_db\"\n"
            "path = \"mod_db.rs\"\n"
            "\n"
            "[dependencies]\n"
            "rusqlite = { version = \"0.41\", features = "
            "[\"bundled\"] }\n"
        )
        self.assertEqual(_bin_name_from_cargo_toml(text), "mod_db")

    def test_package_name_fallback_when_no_bin(self):
        text = (
            "[package]\n"
            "name = \"fallback-pkg\"\n"
            "version = \"1.0.0\"\n"
            "\n"
            "[dependencies]\n"
        )
        self.assertEqual(_bin_name_from_cargo_toml(text),
                         "fallback-pkg")

    def test_no_name_at_all_is_none(self):
        self.assertIsNone(_bin_name_from_cargo_toml(
            "[dependencies]\nserde_json = \"1.0.154\"\n"))


class TestPackageRsHelloSmoke(unittest.TestCase):
    def test_hello_smoke_binary_runs(self):
        if TOOLCHAIN["rustc"] == "unknown":
            self.skipTest("rustc is not installed on this VM")
        before = _staging_leftovers("hello-rs-")
        with tempfile.TemporaryDirectory() as d:
            src = ROOT / "examples" / "hello.newr"
            f = Path(d) / "hello.newr"
            shutil.copyfile(src, f)
            r = run_cli("build", str(f), "--target", "rs", cwd=d)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            emitted = Path(d) / "hello.rs"
            self.assertTrue(emitted.is_file())
            # hello is a plain program: no Cargo.toml, no runtime.
            self.assertFalse((Path(d) / "Cargo.toml").exists())
            dist_dir = Path(d) / "dist" / "hello-rs"
            artifact = package_rs(
                app_name="hello", emitted_dir=Path(d),
                emitted_files=["hello.rs"], main_file="hello.rs",
                dist_dir=dist_dir)
            self.assertEqual(artifact, dist_dir / "hello")
            self.assertTrue(artifact.is_file())
            self.assertGreater(artifact.stat().st_size, 0)
            run = subprocess.run([str(artifact)], capture_output=True,
                                 text=True, timeout=120)
            self.assertEqual(run.returncode, 0, run.stderr)
            self.assertEqual(run.stdout, "Hello, world!\n")
        after = _staging_leftovers("hello-rs-")
        self.assertEqual(after - before, set(),
                         "a successful package must remove its "
                         "staging dir")

    def test_missing_main_file_raises_app_pack_error(self):
        with tempfile.TemporaryDirectory() as d:
            with self.assertRaises(AppPackError) as caught:
                package_rs(
                    app_name="hello", emitted_dir=Path(d),
                    emitted_files=["nope.rs"], main_file="nope.rs",
                    dist_dir=Path(d) / "dist" / "hello-rs")
            # The diagnostic names the failing step, never a
            # traceback: the exception message carries the rustc
            # command and the missing file.
            self.assertIn("rustc", str(caught.exception))
            self.assertIn("nope.rs", str(caught.exception))

    def test_cargo_target_dir_is_under_workspace(self):
        # SPEC section 22.2: the persistent target dir lives under
        # ~/workspace, never /tmp.
        self.assertEqual(
            CARGO_TARGET_DIR,
            Path.home() / "workspace" / ".cargo-target")
        self.assertNotIn("tmp", CARGO_TARGET_DIR.parts)


if __name__ == "__main__":
    unittest.main()
