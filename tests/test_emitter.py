class TestPrecedence(unittest.TestCase):
    def test_unary_minus_takes_the_whole_sum(self):
        # newr: `-a + b` is `-(a + b)` (operand precedence 6) — unlike
        # Python, where it is `(-a) + b`. Ints lower to checked
        # helpers, but the trap is preserved in the nesting: the
        # addition happens FIRST (add), then the negation (neg).
        text = emit_main_text("let a = 1\nlet b = 2\nlet x = -a + b\n"
                              "print x\n")
        self.assertIn("neg(add(a, b))", text)
        # Floats keep the bare operators — and there the
        # parenthesization is visible as text.
        ftext = emit_main_text("let a = 1.0\nlet b = 2.0\n"
                               "let x = -a + b\nprint x\n")
        self.assertIn("-(a + b)", ftext)
        self.assertEqual(run_ok("let a = 1\nlet b = 2\nlet x = -a + b\n"
                                "print x\n"), "-3\n")

    def test_unary_minus_power(self):
        self.assertEqual(run_ok("print -2 ** 2\n"), "-4\n")
        # `print (-2) ** 2` does NOT mean print the power: `print (x)`
        # is a call with a parenthesized argument, so `** 2` would
        # apply to the call's result (none). The power goes in a let.
        self.assertEqual(run_ok("let x = (-2) ** 2\nprint x\n"), "4\n")

    def test_not_takes_the_whole_and(self):
        text = emit_main_text(
            "let a = true\nlet b = false\nlet x = not a and b\nprint x\n")
        self.assertIn("not (a and b)", text)
        self.assertEqual(run_ok(
            "let a = true\nlet b = false\nlet x = not a and b\nprint x\n"),
            "true\n")

    def test_power_is_right_associative(self):
        # `2 ** 3 ** 2` is `2 ** (3 ** 2)` = 512. Ints lower to
        # checked helpers, so the associativity is visible in the
        # nesting (pow_int(2, pow_int(3, 2))); floats lower to
        # pow_float the same way (D28).
        text = emit_main_text("let x = 2 ** 3 ** 2\nprint x\n")
        self.assertIn("pow_int(2, pow_int(3, 2))", text)
        ftext = emit_main_text("let x = 2.0 ** 3.0 ** 2.0\nprint x\n")
        self.assertIn("pow_float(2.0, pow_float(3.0, 2.0))", ftext)
        self.assertEqual(run_ok("print 2 ** 3 ** 2\n"), "512\n")

    def test_parens_preserved_where_needed(self):
        # `print (1 + 2) * 3` does NOT mean print the product: the
        # parenthesized expression is print's argument, so `* 3`
        # would apply to the call's result (none). Parenthesized
        # arithmetic goes in a let (or double parens).
        self.assertEqual(run_ok("let x = (1 + 2) * 3\nprint x\n"), "9\n")
        self.assertEqual(run_ok("print 1 + 2 * 3\n"), "7\n")
        self.assertEqual(run_ok("print 10 - (3 - 1)\n"), "8\n")
        self.assertEqual(run_ok("print true or false and false\n"),
                         "true\n")

    def test_ternary(self):
        self.assertEqual(run_ok("print 1 > 0 ? \"yes\" : \"no\"\n"), "yes\n")
        self.assertEqual(
            run_ok("print false ? 1 : true ? 2 : 3\n"), "2\n")


class TestStringsAndInterpolation(unittest.TestCase):
    def test_bool_interpolates_lowercase(self):
        self.assertEqual(run_ok('print "flag {true} and {false}"\n'),
                         "flag true and false\n")

    def test_literal_braces(self):
        self.assertEqual(run_ok('print "use {{x}} for a set"\n'),
                         "use {x} for a set\n")

    def test_escapes_and_unicode(self):
        src = ('print "tab\\there"\nprint "quote \\"hi\\""\n'
               'print "emoji \\u{1F600} ok"\n')
        self.assertEqual(run_ok(src),
                         "tab\there\nquote \"hi\"\nemoji \U0001F600 ok\n")

    def test_fstring_hoists_backslash(self):
        # A string literal with an escape inside an interpolation is
        # a backslash inside an f-string replacement field — a
        # SyntaxError on Python 3.10/3.11 (PEP 701, P1). The emitter
        # must hoist it to a temp variable.
        src = 'print "got {"a\\nb"}"\n'
        text = emit_main_text(src)
        self.assertIn("_newr_h0", text)
        # No backslash may appear inside any f-string replacement field.
        for m in re.finditer(r"f\"(.*?)\"", text):
            for field in re.findall(r"\{([^{}]*)\}", m.group(1)):
                self.assertNotIn("\\", field, f"backslash in {field!r}")
        self.assertEqual(run_ok(src), "got a\nb\n")

    def test_fstring_alternates_quotes(self):
        # A double-quote inside an interpolated string literal must
        # not reuse the f-string's quote (3.10 rule, P1).
        src = "print \"say {\"hi\"} now\"\n"
        text = emit_main_text(src)
        ast.parse(text)  # must be valid Python on every floor
        self.assertEqual(run_ok(src), "say hi now\n")

    def test_print_renders_collections(self):
        # newr lists are homogeneous, so the P8 rendering is pinned
        # with one list per element type (a mixed `[1, true, "a"]`
        # is a checker error, E2003).
        self.assertEqual(run_ok("print [1, 2, 3]\n"), "[1, 2, 3]\n")
        self.assertEqual(run_ok("print [\"a\", \"b\"]\n"), "[a, b]\n")
        self.assertEqual(run_ok("print [true, false]\n"), "[true, false]\n")
        self.assertEqual(run_ok("print {\"k\": 1}\n"), "{k: 1}\n")
        self.assertEqual(run_ok("print none\n"), "none\n")

    def test_str_builtin(self):
        self.assertEqual(run_ok("print str(true)\nprint str(1.5)\n"),
                         "true\n1.5\n")


