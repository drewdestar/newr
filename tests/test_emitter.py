class TestCollections(unittest.TestCase):
    def test_list_methods(self):
        src = ("let xs = [1, 2]\n"
               "xs.append(3)\n"
               "print xs.len()\n"
               "print 2 in xs\n"
               "print xs.get(5, 99)\n"
               "print xs.get(-1, 99)\n")
        self.assertEqual(run_ok(src), "3\ntrue\n99\n99\n")

    def test_reference_semantics_pinned(self):
        # P12: collections are reference types in v1 — aliasing
        # through .append is observable. This pins the decision.
        src = ("let xs = [1, 2]\n"
               "let ys = xs\n"
               "xs.append(3)\n"
               "print ys\n")
        self.assertEqual(run_ok(src), "[1, 2, 3]\n")

    def test_dict_methods(self):
        src = ("let d = {\"a\": 1}\n"
               "print d.get(\"a\", 0)\n"
               "print d.get(\"zz\", 0)\n"
               "print \"a\" in d\n"
               "print d.keys()\n")
        self.assertEqual(run_ok(src), "1\n0\ntrue\n[a]\n")

    def test_set_ops(self):
        src = ("let s = set([1, 2, 2, 3])\n"
               "print s.contains(2)\n"
               "s.add(4)\n"
               "print s.contains(4)\n"
               "s.remove(1)\n"
               "print s.contains(1)\n")
        self.assertEqual(run_ok(src), "true\ntrue\nfalse\n")

    def test_str_methods(self):
        src = ("print \"Hello\".lower()\n"
               "print \" hello \".strip()\n"
               "print \"a,b,c\".split(\",\")\n"
               "print \",\".join([\"a\", \"b\"])\n"
               "print \"hello\".contains(\"ell\")\n"
               "print \"hello\".starts_with(\"he\")\n"
               "print \"héllo\".chars()\n")
        self.assertEqual(
            run_ok(src),
            "hello\nhello\n[a, b, c]\na,b\ntrue\ntrue\n[h, é, l, l, o]\n")

    def test_range_and_for(self):
        self.assertEqual(run_ok("for i in range(3):\n  print i\n"),
                         "0\n1\n2\n")
        self.assertEqual(run_ok("print range(1, 4)\n"), "[1, 2, 3]\n")


class TestConversions(unittest.TestCase):
    def test_round_half_away(self):
        self.assertEqual(run_ok("print round(2.5)\nprint round(3.5)\n"
                                "print round(-2.5)\nprint round(2.675, 2)\n"),
                         "3\n4\n-3\n2.67\n")

    def test_bool_parse(self):
        self.assertEqual(run_ok("print bool(\"false\")\nprint bool(\"true\")\n"
                                "print bool(0)\nprint bool(3)\n"),
                         "false\ntrue\nfalse\ntrue\n")

    def test_int_float_conversions(self):
        self.assertEqual(run_ok("print int(3.9)\nprint int(-3.9)\n"
                                "print int(\"42\")\nprint float(5)\n"),
                         "3\n-3\n42\n5.0\n")

    def test_time_format_is_utc(self):
        # P4: UTC, not local time — 00:00 at the epoch everywhere.
        self.assertEqual(run_ok("print time.format(0, \"%H:%M\")\n"
                                "print time.format(0, \"%Y-%m-%d\")\n"),
                         "00:00\n1970-01-01\n")

    def test_math(self):
        self.assertEqual(run_ok("print math.sqrt(2.0)\nprint math.floor(1.9)\n"
                                "print math.ceil(1.1)\nprint math.pi\n"),
                         "1.4142135623730951\n1\n2\n3.141592653589793\n")

    def test_min_max_abs(self):
        self.assertEqual(run_ok("print min(3, 7)\nprint max(3, 7)\n"
                                "print abs(-5)\nprint abs(2.5)\n"),
                         "3\n7\n5\n2.5\n")

    def test_env_args(self):
        self.assertEqual(run_ok("print env.args.len()\n",
                                argv=["a", "b"]),
                         "3\n")


class TestEmitErrors(unittest.TestCase):
    def test_unchecked_program_refuses_cleanly(self):
        # The emitter only runs on a checked program: a node without
        # a type is a clean EmitterError, never an AttributeError
        # traceback from inside the emitter.
        from compiler.parser import parse
        prog = parse('let x = 1 + "a"\n')
        with self.assertRaises(EmitterError):
            emit_program(prog, main_path="<test>.newr",
                         sources={"<test>.newr": 'let x = 1 + "a"\n'})

    def test_empty_program_emits_header_only(self):
        text = emit_main_text("# just a comment\n")
        self.assertTrue(text.startswith("# Generated by newr"))
        ast.parse(text)


class TestFileImport(unittest.TestCase):
    def test_module_emitted_as_separate_file(self):
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / "items.newr").write_text(
                'pub fn price(item: str) -> int:\n'
                '  if item == "brick":\n'
                '    return 118\n'
                '  return 0\n', encoding="utf-8")
            main = Path(d) / "main.newr"
            main.write_text('import "items.newr"\n'
                            'print items.price("brick")\n',
                            encoding="utf-8")
            resolved = resolve_file(main)
            diags = list(resolved.diagnostics)
            diags += check_program(
                resolved.program,
                providers=discord_providers(resolved.program)).diagnostics
            diags += check_discord(resolved.program)
            errs = [x for x in diags if x.is_error()]
            assert not errs, errs
            sources = {
                str(main): main.read_text(encoding="utf-8"),
                str(Path(d) / "items.newr"):
                    (Path(d) / "items.newr").read_text(encoding="utf-8"),
            }
            result = emit_program(resolved.program, main_path=str(main),
                                  sources=sources)
            self.assertIn("main.py", result.files)
            self.assertIn("items.py", result.files)
            self.assertIn("import items", result.files["main.py"])
            # And it runs.
            for name, text in result.files.items():
                (Path(d) / name).write_text(text, encoding="utf-8")
            proc = subprocess.run(
                [sys.executable, str(Path(d) / "main.py")],
                capture_output=True, text=True, cwd=d)
            self.assertEqual(proc.returncode, 0, proc.stderr)
            self.assertEqual(proc.stdout, "118\n")


