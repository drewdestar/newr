"""Tests for the Python emitter (compiler/emitter.py, M2).

TDD RED first: written before the emitter existed. The `emit_src`
helper runs the full front-end pipeline (resolve + core check +
discord check) and emits Python; `run_src` also executes the emitted
program in a fresh interpreter and returns its stdout.

Every test pins a decision from BUILD_REPORT.md §14 (pins P1–P12,
decisions D1–D27) or a SPEC rule the emitter must preserve —
including the precedence traps (`-a + b` is `-(a + b)` in newr,
unlike Python) and the f-string 3.10 safety rule (P1).
"""

import ast
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from compiler.checker import check_program
from compiler.discord_check import check_discord, discord_providers
from compiler.emitter import EmitterError, emit_program
from compiler.resolver import resolve_file, resolve_source

ROOT = Path(__file__).resolve().parent.parent
RT_SRC = ROOT / "compiler" / "newr_rt.py"


def full_program(src, filename="<test>.newr"):
    """Resolve + check a source string; assert it is clean."""
    resolved = resolve_source(src, filename)
    diags = list(resolved.diagnostics)
    diags += check_program(
        resolved.program,
        providers=discord_providers(resolved.program)).diagnostics
    diags += check_discord(resolved.program)
    errs = [d for d in diags if d.is_error()]
    assert not errs, [f"{d.code}: {d.message}" for d in errs]
    return resolved.program


def emit_src(src, filename="<test>.newr"):
    """Emit a checked program; returns the EmitResult."""
    program = full_program(src, filename)
    return emit_program(program, main_path=filename,
                        sources={filename: src})


def emit_main_text(src, filename="<test>.newr"):
    """The emitted text of the main output file."""
    result = emit_src(src, filename)
    return result.files[result.main_file]


def run_src(src, filename="<test>.newr", argv=None):
    """Emit to a temp dir, copy newr_rt.py if needed, run it.

    Returns (stdout, stderr, returncode).
    """
    result = emit_src(src, filename)
    with tempfile.TemporaryDirectory() as d:
        for name, text in result.files.items():
            (Path(d) / name).write_text(text, encoding="utf-8")
        if result.uses_rt:
            (Path(d) / "newr_rt.py").write_text(
                RT_SRC.read_text(encoding="utf-8"), encoding="utf-8")
        proc = subprocess.run(
            [sys.executable, str(Path(d) / result.main_file),
             *(argv or [])],
            capture_output=True, text=True, cwd=d)
        return proc.stdout, proc.stderr, proc.returncode


def run_ok(src, filename="<test>.newr", argv=None):
    stdout, stderr, code = run_src(src, filename, argv)
    assert code == 0, f"exit {code}\nstdout: {stdout}\nstderr: {stderr}"
    return stdout


