class TestErrorsAndResult(unittest.TestCase):
    def test_throw_string_and_catch_message(self):
        src = ("try:\n"
               "  throw \"something broke\"\n"
               "catch e:\n"
               "  print e.message\n")
        self.assertEqual(run_ok(src), "something broke\n")

    def test_catch_wraps_python_errors(self):
        src = ("try:\n"
               "  let s = int(\"abc\")\n"
               "  print \"nope\"\n"
               "catch e:\n"
               "  print e.message\n"
               "  print e.code\n")
        out = run_ok(src)
        self.assertIn("invalid literal", out)
        self.assertIn("ValueError", out)

    def test_finally_runs(self):
        src = ("try:\n"
               "  throw \"x\"\n"
               "catch e:\n"
               "  print \"caught\"\n"
               "finally:\n"
               "  print \"finally\"\n")
        self.assertEqual(run_ok(src), "caught\nfinally\n")

    def test_try_expr_returns_result(self):
        src = ("let r = try int(\"42\")\n"
               "print r.is_ok()\n"
               "print r.unwrap()\n"
               "let bad = try int(\"xx\")\n"
               "print bad.is_err()\n"
               "print bad.unwrap_or(7)\n")
        self.assertEqual(run_ok(src), "true\n42\ntrue\n7\n")

    def test_propagate_unwraps_and_returns_early(self):
        src = ("fn get(n: int) -> Result[int, error]:\n"
               "  let r = try int(\"xx\")\n"
               "  let v = r?\n"
               "  return ok(v + 1)\n"
               "let out = get(0)\n"
               "print out.is_err()\n")
        self.assertEqual(run_ok(src), "true\n")

    def test_propagate_nullable(self):
        src = ("fn first(xs: list[int]) -> int?:\n"
               "  if xs.len() == 0:\n"
               "    return none\n"
               "  return xs[0]\n"
               "fn pick(xs: list[int]) -> int?:\n"
               "  let v: int? = first(xs)\n"
               "  let w = v?\n"
               "  return w\n"
               "print pick([5])\n"
               "print pick([])\n")
        # pick([]) propagates the none — the function returns none,
        # and printing none renders "none".
        self.assertEqual(run_ok(src), "5\nnone\n")

    def test_propagate_mismatched_kind_is_emitter_error(self):
        # Checker gap (recorded in BUILD_REPORT §14.3): `?` on a
        # nullable inside a Result-returning function has no defined
        # early-return value (there is no Err to return, and the
        # function does not return a nullable). The checker accepts
        # it; the emitter refuses cleanly rather than inventing
        # semantics. The same holds for the reverse mismatch.
        src = ("fn get(n: int) -> Result[int, error]:\n"
               "  let v: int? = none\n"
               "  let w = v?\n"
               "  return ok(w)\n")
        with self.assertRaises(EmitterError):
            emit_src(src)


